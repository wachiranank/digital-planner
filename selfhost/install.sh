#!/usr/bin/env bash
# One-time setup on a fresh Ubuntu VPS (e.g. Hostinger KVM). Safe to re-run: never overwrites an existing .env.
set -euo pipefail
cd "$(dirname "$0")"

say() { printf "\n\033[1;32m==> %s\033[0m\n" "$*"; }
ask() { local var=$1 prompt=$2 def=${3:-}; read -r -p "$prompt${def:+ [$def]}: " val; printf -v "$var" '%s' "${val:-$def}"; }
rand() { openssl rand -hex "${1:-32}"; }
b64url() { openssl base64 -A | tr '+/' '-_' | tr -d '='; }
jwt() { # jwt <role> — HS256 key signed with JWT_SECRET, valid 10 years
  local now exp h p s; now=$(date +%s); exp=$((now + 315360000))
  h=$(printf '{"alg":"HS256","typ":"JWT"}' | b64url)
  p=$(printf '{"role":"%s","iss":"supabase","iat":%d,"exp":%d}' "$1" "$now" "$exp" | b64url)
  s=$(printf '%s.%s' "$h" "$p" | openssl dgst -sha256 -hmac "$JWT_SECRET" -binary | b64url)
  printf '%s.%s.%s' "$h" "$p" "$s"
}

docker network create edge >/dev/null 2>&1 || true # shared network (see sites/README.md)

# 1) Docker
if ! command -v docker >/dev/null 2>&1; then
  say "Installing Docker"
  curl -fsSL https://get.docker.com | sh
fi
docker compose version >/dev/null

# 2) Settings (.env)
if [ -f .env ]; then
  say ".env already exists — keeping it (edit it by hand to change settings)"
else
  say "Settings"
  ask BASE_DOMAIN "Your domain (e.g. example.com)"
  ask PLANNER_DOMAIN "Planner address" "app.$BASE_DOMAIN"
  ask STORE_DOMAIN "Store address" "shop.$BASE_DOMAIN"
  ask API_DOMAIN "API address" "api.$BASE_DOMAIN"
  ask ADMIN_EMAIL "Admin email (for HTTPS certificates)"
  ask GOOGLE_CLIENT_ID "Google OAuth Client ID (can fill in later)" ""
  ask GOOGLE_CLIENT_SECRET "Google OAuth Client secret (can fill in later)" ""

  JWT_SECRET=$(rand 32)
  say "Generating push-notification keys"
  VAPID_JSON=$(docker run --rm node:22-alpine npx -y web-push@3 generate-vapid-keys --json)
  VAPID_PUBLIC_KEY=$(echo "$VAPID_JSON" | sed -E 's/.*"publicKey":"([^"]+)".*/\1/')
  VAPID_PRIVATE_KEY=$(echo "$VAPID_JSON" | sed -E 's/.*"privateKey":"([^"]+)".*/\1/')

  umask 077
  cat > .env <<ENV
# ---- generated by install.sh on $(date -u +%F) — keep this file private ----
PLANNER_DOMAIN=$PLANNER_DOMAIN
STORE_DOMAIN=$STORE_DOMAIN
API_DOMAIN=$API_DOMAIN
ADMIN_EMAIL=$ADMIN_EMAIL

# database + login secrets (do not change after first start)
POSTGRES_PASSWORD=$(rand 24)
JWT_SECRET=$JWT_SECRET
ANON_KEY=$(jwt anon)
SERVICE_ROLE_KEY=$(jwt service_role)
CRON_SECRET=$(rand 24)
VAPID_PUBLIC_KEY=$VAPID_PUBLIC_KEY
VAPID_PRIVATE_KEY=$VAPID_PRIVATE_KEY

# Google sign-in + Calendar
GOOGLE_CLIENT_ID=$GOOGLE_CLIENT_ID
GOOGLE_CLIENT_SECRET=$GOOGLE_CLIENT_SECRET

# Stripe (store payments)
STRIPE_SECRET_KEY=
STRIPE_WEBHOOK_SECRET=

# Optional: license email copy (Resend), file downloads (Cloudflare R2), LINE
RESEND_API_KEY=
EMAIL_FROM=
R2_ACCOUNT_ID=
R2_ACCESS_KEY_ID=
R2_SECRET_ACCESS_KEY=
R2_BUCKET=
STORE_LINE_CHANNEL_ACCESS_TOKEN=
STORE_LINE_OWNER_USER_ID=
PLANNER_LINE_CHANNEL_SECRET=
PLANNER_LINE_CHANNEL_ACCESS_TOKEN=
PLANNER_LINE_BOT_BASIC_ID=

# Images (pin a version, e.g. :1.2.0, for predictable updates)
STORE_IMAGE=ghcr.io/wachiranank/digital-product-store:latest
PLANNER_IMAGE=ghcr.io/wachiranank/digital-planner:latest
ENV
  say ".env created"
fi
set -a; . ./.env; set +a
if [ "${NO_START:-}" = "1" ]; then say "NO_START=1 — .env ready, not starting"; exit 0; fi

# 3) Private images on GitHub Container Registry
if ! docker pull -q "$PLANNER_IMAGE" >/dev/null 2>&1; then
  say "Log in to ghcr.io (GitHub username + a token with read:packages)"
  docker login ghcr.io
fi

# 4) Start everything
say "Starting (first start downloads images, takes a few minutes)"
docker compose pull
docker compose up -d

# 5) Daily backup at 03:00
CRON_LINE="0 3 * * * cd $(pwd) && ./backup.sh >> backups/backup.log 2>&1"
mkdir -p backups
( crontab -l 2>/dev/null | grep -v "digital-suite-backup" ; echo "$CRON_LINE # digital-suite-backup" ) | crontab -

say "Done!"
cat <<MSG
  Planner : https://$PLANNER_DOMAIN
  Store   : https://$STORE_DOMAIN
  API     : https://$API_DOMAIN

Next (see README):
  • Google Cloud → OAuth client → Authorized redirect URI: https://$API_DOMAIN/auth/v1/callback
  • Stripe → webhook: https://$STORE_DOMAIN/api/webhooks/stripe  → put keys in .env, then: docker compose up -d
  • LINE (optional) → webhook: https://$PLANNER_DOMAIN/api/line/webhook
MSG
